"""
test_unit_circle.py — the post-fit unit-circle node move (libena's
move_nodes_to_unit_circle) against R.

fixtures/unit-circle-rs.json holds R reference values on RS.data, from the R
implementation libena replaced (generated by
wasm/test/fixtures/unit-circle-rs.R; the same file rena-wasm tests).
"""

from __future__ import annotations

import json
import pathlib

import numpy as np
import pandas as pd
import pytest

from ena import ENA, libena

HERE    = pathlib.Path(__file__).parent
FIXTURE = json.loads((HERE / "fixtures/unit-circle-rs.json").read_text())
RS_CSV  = HERE / "../../inst/extdata/rs.data.csv"

RS_CODES = ["Data", "Technical Constraints", "Performance Parameters",
            "Client and Consultant Requests", "Design Reasoning", "Collaboration"]


def _model(name):
    m = FIXTURE["models"][name]
    return np.array(m["line_weights"]), np.array(m["nodes"]), m["directed"]


@pytest.mark.parametrize("case", FIXTURE["cases"],
                         ids=lambda c: f'{c["model"]}-{c["mode"]}-{c["dims"]}')
def test_matches_r(case):
    lw, nodes, directed = _model(case["model"])
    r = libena.move_nodes_to_unit_circle(lw, nodes, *case["dims"],
                                         mode=case["mode"], directed=directed)
    np.testing.assert_allclose(r.nodes, np.array(case["nodes"]), rtol=1e-10, atol=1e-12)
    np.testing.assert_allclose(r.centroids, np.array(case["centroids"]), rtol=1e-10, atol=1e-12)


def test_defaults_are_equal_mode_on_the_first_two_dims():
    lw, nodes, _ = _model("unordered")
    case = next(c for c in FIXTURE["cases"]
                if c["model"] == "unordered" and c["mode"] == "equal" and c["dims"] == [0, 1])
    r = libena.move_nodes_to_unit_circle(lw, nodes)
    np.testing.assert_allclose(r.nodes, np.array(case["nodes"]), rtol=1e-10, atol=1e-12)


def test_bad_arguments_raise():
    lw, nodes, _ = _model("unordered")
    with pytest.raises(ValueError, match="equal"):
        libena.move_nodes_to_unit_circle(lw, nodes, mode="spiral")
    with pytest.raises(ValueError, match="out of range"):
        libena.move_nodes_to_unit_circle(lw, nodes, 0, nodes.shape[1])
    with pytest.raises(ValueError, match="differ"):
        libena.move_nodes_to_unit_circle(lw, nodes, 1, 1)
    with pytest.raises(ValueError, match=">= 0"):
        libena.move_nodes_to_unit_circle(lw, nodes, -1, 1)
    with pytest.raises(ValueError, match="columns"):
        libena.move_nodes_to_unit_circle(lw, nodes, directed=True)


@pytest.mark.skipif(not RS_CSV.exists(), reason="rs.data.csv from the rENA repo not found")
def test_ena_method_returns_a_moved_copy():
    rs = pd.read_csv(RS_CSV)
    rs["unit_key"]  = rs["Condition"] + "::" + rs["UserName"]
    rs["convo_key"] = rs["Condition"] + "::" + rs["GroupName"]
    model = ENA().fit(rs, "unit_key", "convo_key", RS_CODES, window_size=4, dims=4)
    nodes_before = model.rotation_nodes_.copy()
    centroids_before = model.centroids_.copy()

    for mode in ("equal", "radial"):
        moved = model.move_nodes_to_unit_circle(dims=(2, 1), mode=mode)

        # the fitted model is unchanged
        np.testing.assert_array_equal(model.rotation_nodes_, nodes_before)
        np.testing.assert_array_equal(model.centroids_, centroids_before)

        # same as the low-level call; points and other dims kept
        low = libena.move_nodes_to_unit_circle(model.line_weights_, nodes_before, 2, 1, mode=mode)
        np.testing.assert_array_equal(moved.rotation_nodes_, low.nodes)
        np.testing.assert_array_equal(moved.centroids_, low.centroids)
        assert moved.points_ is model.points_
        np.testing.assert_array_equal(moved.rotation_nodes_[:, [0, 3]], nodes_before[:, [0, 3]])

        # on the circle; centroids are the fit's node weights times the moved nodes
        radii = np.hypot(moved.rotation_nodes_[:, 2], moved.rotation_nodes_[:, 1])
        np.testing.assert_allclose(radii, np.hypot(nodes_before[:, 2], nodes_before[:, 1]).max(),
                                   rtol=1e-12)
        np.testing.assert_allclose(moved.centroids_, model.weights_ @ moved.rotation_nodes_,
                                   rtol=1e-10, atol=1e-12)
